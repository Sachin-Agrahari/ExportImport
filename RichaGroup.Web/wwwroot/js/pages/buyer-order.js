window.orderMode = function (btn, mode) {
    var $btn = $(btn);
    var $parent = $btn.closest(".segment");

    if ($parent.length) {
        $parent.find("button").removeClass("on");
        $btn.addClass("on");
    }

    $("#mode-add").toggle(mode === "add");
    $("#mode-upd").toggle(mode === "upd");
};


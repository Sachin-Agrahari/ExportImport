function escapeHtml(str) {
    if (!str) return '';
    return String(str).replace(/[&<>"']/g, function (c) {
        return {
            '&': '&amp;',
            '<': '&lt;',
            '>': '&gt;',
            '"': '&quot;',
            "'": '&#39;'
        }[c];
    });
}

function buildByrNameOptions(row) {
    const options = [row.byrName
        ? `<option value="${escapeHtml(row.byrCode || '')}" selected>${escapeHtml(row.byrName)}</option>`
        : `<option value="" selected>Select&hellip;</option>`];

    (row.byrOptions || []).forEach(opt => {
        if (row.byrName && opt.text === row.byrName) return;
        options.push(`<option value="${escapeHtml(opt.value)}">${escapeHtml(opt.text)}</option>`);
    });

    return options.join('');
}


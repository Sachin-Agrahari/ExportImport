function renderOrdersAddGrid(data) {
    var $body = $("#tblOrdersAddBody");
    if (!$body.length) return;

    $body.html($.map(data, function (row, index) {
        return buildOrdersAddRow(row, index);
    }).join(""));
     
    $body.find("input[type='checkbox']").each(function () {
        $(this).closest("tr").toggleClass("selected", this.checked);
    });
}

 
function switchView(name) {
    
    $(".view").each(function () {
        var isTarget = this.id === "view-" + name; 
        $(this).toggleClass("on", isTarget) .toggle(isTarget);
    });

    $(".screen-switch button").removeClass("on") .filter(function () {
        return $(this).data("view") === name;
    }).addClass("on");

    window.scrollTo({ top: 0,  behavior: "smooth" });
}

// Top view buttons
$(document).on("click", ".screen-switch button", function (e) {
    e.preventDefault();
    e.stopPropagation();
    switchView($(this).data("view"));
});


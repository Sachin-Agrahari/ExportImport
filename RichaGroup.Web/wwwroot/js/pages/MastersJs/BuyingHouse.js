function renderBuyingHouseTable(data) {

    var $tbody = $("#tblBuyingHouseMasterBody");

    $tbody.empty();

    if (!data || data.length === 0) {

        $("#noRecordsFound_BuyingHouse").removeClass("d-none");
        $("#tblBuyingHouseMaster").addClass("d-none");

        return;
    }

    $("#noRecordsFound_BuyingHouse").addClass("d-none");
    $("#tblBuyingHouseMaster").removeClass("d-none");

    $.each(data, function (index, row) {

        var tr = `
            <tr>
                <td>
                     <button
                        type="button"
                        class="row-btn edit-btn"
                        title="Edit"
                        onclick="EditMatser('${row.buyingHouseName}')"
                        data-code="${row.buyingHouseName}">
                        <i class="fa-solid fa-pen-to-square"></i>
                    </button>
                </td>
                <td>
                    <span class="badge btn-primary">
                        ${row.code}
                    </span>
                </td>

                <td>${row.buyingHouseName}</td>
                <td>${row.aliasName}</td>
                <td>${row.city}</td>
                <td>${row.state}</td>
                <td>${row.country}</td>
                <td>${row.email}</td>
                 
            </tr>
        `;

        $tbody.append(tr);
    });
}


function saveBuyingHouse() {

    var buyingHouseName = $("#txtBuyingHouseName").val().trim();
    var aliasName = $("#txtAliasName").val().trim();
    var address1 = $("#txtAddress1").val().trim();
    var city = $("#txtCity").val().trim();
    var state = $("#txtState").val().trim();
    var country = $("#ddlCountry").val();
    var email = $("#txtEmail").val().trim();

    if (buyingHouseName === "") {
        showWarning("Validation", "Please enter Buying House Name.");
        return;
    }

    if (aliasName === "") {
        showWarning("Validation", "Please enter Alias Name.");
        return;
    }

    if (address1 === "") {
        showWarning("Validation", "Please enter Address 1.");
        return;
    }

    if (city === "") {
        showWarning("Validation", "Please enter City.");
        return;
    }

    if (state === "") {
        showWarning("Validation", "Please enter State.");
        return;
    }

    if (country === "") {
        showWarning("Validation", "Please select Country.");
        return;
    }

    if (email === "") {
        showWarning("Validation", "Please enter Email.");
        return;
    }

    var buyingHouseRecord = {
        code: BuyingHouseID || new Date().getTime(),
        buyingHouseName: buyingHouseName,
        aliasName: aliasName,
        address1: address1,
        address2: $("#txtAddress2").val().trim(),
        address3: $("#txtAddress3").val().trim(),
        address4: $("#txtAddress4").val().trim(),
        city: city,
        state: state,
        country: country,
        pinCode: $("#txtPinCode").val().trim(),
        contact1: $("#txtContact1").val().trim(),
        contact2: $("#txtContact2").val().trim(),
        telephone: $("#txtTelephone").val().trim(),
        fax: $("#txtFax").val().trim(),
        email: email,
        otherInformation: $("#txtOtherInformation").val().trim()
    };

    console.log("Buying House Saved:", buyingHouseRecord);

    showSuccess(
        "Success",
        "Buying House saved successfully."
    ).then(function () {
        window.location.href = "/Master/ViewBuyingHouse";
    });

}

 
// ==========================================
// Render CHA Table
// ==========================================

function renderCHATable(data) {

    var $tbody = $("#tblCHAMasterBody");

    $tbody.empty();

    if (!data || data.length === 0) {

        $("#noRecordsFound_CHA").removeClass("d-none");
        $("#tblCHAMaster").addClass("d-none");

        return;
    }

    $("#noRecordsFound_CHA").addClass("d-none");
    $("#tblCHAMaster").removeClass("d-none");

    $.each(data, function (index, row) {

        var tr = `<tr>

            <td>
                  <button
                     type="button"
                     class="row-btn edit-btn"
                     title="Edit"
                     onclick="EditMatser('${row.code}')"
                     data-code="${row.code}">
                       <i class="fa-solid fa-pen-to-square"></i>
                 </button>
             </td>

             <td>
                 <span class="badge btn-primary">
                     ${row.code}
                 </span>
             </td>

             <td>${row.chaName}</td>
             <td>${row.aliasName}</td>
             <td>${row.warehouseCity}</td>
             <td>${row.city}</td>
             <td>${row.state}</td>
             <td>${row.country}</td>
             <td>${row.email}</td>
 
        </tr>`;

        $tbody.append(tr);
    });
}



// ==========================================
// Refresh CHA List
// ==========================================

function refreshCHA() {

    showLoader("Refreshing...");

    try {

        renderCHATable(chaMasterData);

        setTimeout(function () {
            hideLoader();
        }, 1000);

    } catch (error) {

        console.error(
            "[CHAMaster] Refresh failed:",
            error
        );

        hideLoader();
    }

}



function loadCHADetails(id) {

    var record = chaMasterData.find(function (item) {
        return item.code == id;
    });

    if (!record) {
        return;
    }

    $("#txtCHAName").val(record.chaName);
    $("#txtAliasName").val(record.aliasName);

    $("#txtWarehouseAddress").val(record.warehouseAddress);
    $("#txtAddress").val(record.address);

    $("#txtWarehouseCity").val(record.warehouseCity);
    $("#txtCity").val(record.city);

    $("#txtWarehouseState").val(record.warehouseState);
    $("#txtState").val(record.state);

    $("#ddlWarehouseCountry").val(record.warehouseCountry);
    $("#ddlCountry").val(record.country);

    $("#txtContact1").val(record.contact1);
    $("#txtContact2").val(record.contact2);

    $("#txtTelephone").val(record.telephone);
    $("#txtFax").val(record.fax);

    $("#txtEmail").val(record.email);
    $("#txtPinCode").val(record.pinCode);

    $("#txtOtherInformation").val(record.otherInformation);

}


// ==========================================
// Save CHA
// ==========================================

function saveCHA() {

    var chaName = $("#txtCHAName").val().trim();
    var aliasName = $("#txtAliasName").val().trim();
    var warehouseAddress = $("#txtWarehouseAddress").val().trim();
    var address = $("#txtAddress").val().trim();
    var country = $("#ddlCountry").val();
    var email = $("#txtEmail").val().trim();

    if (chaName === "") {
        showWarning("Validation", "Please enter CHA Name.");
        return;
    }

    if (aliasName === "") {
        showWarning("Validation", "Please enter Alias Name.");
        return;
    }

    if (warehouseAddress === "") {
        showWarning("Validation", "Please enter Warehouse Address.");
        return;
    }

    if (address === "") {
        showWarning("Validation", "Please enter Address.");
        return;
    }

    if (country === "") {
        showWarning("Validation", "Please select Country.");
        return;
    }

    if (email === "") {
        showWarning("Validation", "Please enter Email.");
        return;
    }

    var chaRecord = {
        code: CHAID || new Date().getTime(),
        chaName: chaName,
        aliasName: aliasName,
        warehouseAddress: warehouseAddress,
        address: address,
        warehouseCity: $("#txtWarehouseCity").val().trim(),
        city: $("#txtCity").val().trim(),
        warehouseState: $("#txtWarehouseState").val().trim(),
        state: $("#txtState").val().trim(),
        warehouseCountry: $("#ddlWarehouseCountry").val(),
        country: country,
        contact1: $("#txtContact1").val().trim(),
        contact2: $("#txtContact2").val().trim(),
        telephone: $("#txtTelephone").val().trim(),
        fax: $("#txtFax").val().trim(),
        email: email,
        pinCode: $("#txtPinCode").val().trim(),
        otherInformation: $("#txtOtherInformation").val().trim()
    };

    console.log("CHA Saved:", chaRecord);

    showSuccess(
        "Success",
        "CHA saved successfully."
    ).then(function () {
        window.location.href = "/Master/ViewCHA";
    });

}



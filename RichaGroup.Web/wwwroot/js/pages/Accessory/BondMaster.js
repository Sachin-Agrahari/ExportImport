// ==========================================
// Save Bond Master
// ==========================================

function saveBondMaster() {

    let bondRecord = {

        code: BondID || getNextBondCode(),

        entryNumber:
            $("#txtEntryNumber_BondMaster").val().trim(),

        companyCode:
            $("#txtCompanyCode_BondMaster").val().trim(),

        certificateNo:
            $("#txtCertificateNo_BondMaster").val().trim(),

        exportBondNo:
            $("#txtExportBondNo_BondMaster").val().trim(),

        exportBondDate:
            $("#txtExportBondDate_BondMaster").val().trim(),

        countryOrigin:
            $("#txtCountryOrigin_BondMaster").val().trim(),

        supplierInvNo:
            $("#txtSupplierInvNo_BondMaster").val().trim(),

        supplierInvDate:
            $("#txtSupplierInvDate_BondMaster").val().trim(),

        awbHawbNo:
            $("#txtAwbHawbNo_BondMaster").val().trim(),

        awbHawbDate:
            $("#txtAwbHawbDate_BondMaster").val().trim(),

        billEntryNo:
            $("#txtBillEntryNo_BondMaster").val().trim(),

        billEntryDate:
            $("#txtBillEntryDate_BondMaster").val().trim(),

        exportBondAssValue:
            $("#txtExportBondAssValue_BondMaster").val().trim(),

        exportBondTotalValue:
            $("#txtExportBondTotalValue_BondMaster").val().trim(),

        exportBondValidMonth:
            $("#txtExportBondValidMonth_BondMaster").val().trim(),

        qty:
            $("#txtQty_BondMaster").val().trim(),

        houseAwbNo:
            $("#txtHouseAwbNo_BondMaster").val().trim(),

        houseAwbDate:
            $("#txtHouseAwbDate_BondMaster").val().trim(),

        igm:
            $("#txtIGM_BondMaster").val().trim(),

        igmDate:
            $("#txtIGMDate_BondMaster").val().trim()

    };


    // Basic Validation

    if (!bondRecord.entryNumber) {

        showWarning(
            "Validation",
            "Please enter Entry Number."
        );

        $("#txtEntryNumber_BondMaster").focus();

        return;
    }

    if (!bondRecord.companyCode) {

        showWarning(
            "Validation",
            "Please enter Company Code."
        );

        $("#txtCompanyCode_BondMaster").focus();

        return;
    }

    if (!bondRecord.exportBondNo) {

        showWarning(
            "Validation",
            "Please enter Export Bond Number."
        );

        $("#txtExportBondNo_BondMaster").focus();

        return;
    }


    if (BondID) {

        let index = bondMasterData.findIndex(function (item) {
            return item.code == BondID;
        });

        if (index !== -1) {
            bondMasterData[index] = bondRecord;
        }

    } else {

        bondMasterData.push(bondRecord);

    }

    showSuccess(
        "Success",
        BondID
            ? "Bond details updated successfully."
            : "Bond details saved successfully."
    ).then(function () {

        window.location.href = "/MasterNew/ViewBond";

    });

}



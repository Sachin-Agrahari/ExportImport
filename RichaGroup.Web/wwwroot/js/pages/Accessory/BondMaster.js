function filterBondTable() {
  
    let filterValue = $("#txtSearchBondDetails").val().toLowerCase();

    
    let $rows = $("#tblBondDetailsMasterBody tr");

    
    $rows.each(function () {
        let rowText = $(this).text().toLowerCase();

        if (rowText.indexOf(filterValue) > -1) {
            $(this).show(); 
        } else {
            $(this).hide(); 
        }
    });

    
    let visibleRowsCount = $("#tblBondDetailsMasterBody tr:visible").length;
    if (visibleRowsCount === 0) {
        $("#noRecordsFound_BondDetailsMaster").removeClass("d-none");
    } else {
        $("#noRecordsFound_BondDetailsMaster").addClass("d-none");
    }
}


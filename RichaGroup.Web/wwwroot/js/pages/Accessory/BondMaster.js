// ==========================================
// Generate New Bond Code
// ==========================================

function getNextBondCode() {

    if (bondMasterData.length === 0) {
        return 1001;
    }

    return Math.max.apply(
        null,
        bondMasterData.map(function (item) {
            return item.code;
        })
    ) + 1;

}


